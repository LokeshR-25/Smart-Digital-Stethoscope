static void send_chunk(uint16_t *p, size_t n)
{
    char line[16];
    // Send every 8th sample → effective ~125 Hz rate
    for (size_t i = 0; i < n; i += 8)
    {
        int len = sprintf(line, "%u\r\n", p[i]);
        HAL_UART_Transmit(&huart1, (uint8_t*)line, len, HAL_MAX_DELAY);
        HAL_Delay(1); // pacing to avoid HC-05 overflow
    }
}
